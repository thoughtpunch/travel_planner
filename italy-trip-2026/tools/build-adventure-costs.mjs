/* build-adventure-costs.mjs — researched party-of-6 prices → public/adventure-costs.js
 *
 * Input:  <scratch>/legs/leg<N>-out.json, produced by the pricing research pass.
 *         Each row: { idx, name, eur6Lo, eur6Hi, note, confidence, source }
 * Output: public/adventure-costs.js — window.ADVENTURE_COSTS keyed by the SAME
 *         stable slug adventures.html builds (leg + '-' + slugified title), so a
 *         reordered data file doesn't silently mis-attach prices.
 *
 *   node tools/build-adventure-costs.mjs [inputDir]
 *
 * Rows the parser in party-cost.js already handles are NOT in here — this file
 * only carries what had to be looked up. adventures.html prefers this over the
 * parse, and falls back to the parse, and shows "—" if it has neither.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IN = process.argv[2] || '/private/tmp/claude-501/-Users-dan-sites-thoughtpunch-trip-planner/41e8d5f8-6fb5-4cae-85b5-af2307f02851/scratchpad/legs';
const OUT = path.join(ROOT, 'public', 'adventure-costs.js');

// must byte-for-byte match slug() in adventures.html
const slug = (leg, n) => leg + '-' + String(n).toLowerCase().normalize('NFKD')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60);

// load the canonical adventure list so we can map idx → the real title/leg
globalThis.window = {};
const dataSrc = fs.readFileSync(path.join(ROOT, 'public', 'adventures-data.js'), 'utf8');
new Function(dataSrc).call(globalThis);
const ADV = globalThis.window.TRIP_ADVENTURES;

const out = {};
let n = 0, low = 0, skipped = [];

for (const f of fs.readdirSync(IN).filter(f => /^leg\d+-out\.json$/.test(f)).sort()) {
  let rows;
  try { rows = JSON.parse(fs.readFileSync(path.join(IN, f), 'utf8')); }
  catch (e) { console.warn(`  ⚠︎ ${f}: unreadable (${e.message}) — skipped`); continue; }
  if (!Array.isArray(rows)) { console.warn(`  ⚠︎ ${f}: not an array — skipped`); continue; }

  for (const r of rows) {
    const item = ADV[r.idx];
    if (!item) { skipped.push(`${f} idx ${r.idx} out of range`); continue; }
    // guard against a shifted data file: the researched name must still match
    if (r.name && item.n && r.name.slice(0, 25) !== item.n.slice(0, 25)) {
      skipped.push(`${f} idx ${r.idx}: "${r.name}" ≠ "${item.n}"`); continue;
    }
    const lo = Number(r.eur6Lo), hi = Number(r.eur6Hi);
    if (!Number.isFinite(lo) || !Number.isFinite(hi)) { skipped.push(`${f} idx ${r.idx}: non-numeric`); continue; }
    out[slug(item.leg, item.n)] = {
      lo, hi: Math.max(lo, hi),
      note: (r.note || '').slice(0, 90),
      conf: r.confidence || 'medium',
      src: r.source || '',
    };
    n++;
    if (r.confidence === 'low') low++;
  }
}

const esc = s => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const body = Object.entries(out)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([k, v]) => `  '${esc(k)}': { lo:${v.lo}, hi:${v.hi}, note:'${esc(v.note)}', conf:'${v.conf}' },`)
  .join('\n');

fs.writeFileSync(OUT, `/* ============================================================================
 * adventure-costs.js — GENERATED by tools/build-adventure-costs.mjs. Do not edit.
 * Researched total cost for the party of SIX, in EUR, per activity.
 * Key = the stable slug adventures.html derives from leg + title.
 * ==========================================================================*/
window.ADVENTURE_COSTS = {
${body}
};
`);

console.log(`adventure-costs.js written — ${n} priced (${low} low-confidence)`);
if (skipped.length) {
  console.log(`  ${skipped.length} skipped:`);
  skipped.slice(0, 12).forEach(s => console.log('    ' + s));
}
